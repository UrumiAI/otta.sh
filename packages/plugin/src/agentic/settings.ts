/**
 * Agentic checkout's settings (ADR-0047), plain plugin kv beside cash on delivery's.
 *
 *  - `settings:agenticEnabled` — the toggle, saved from the Agentic checkout group
 *    of the Store settings page. ONLY a stored `true` turns it on: a store that
 *    never saved it, a kv miss, a failed read or any other value reads as OFF, and
 *    every agentic route then answers `NOT_FOUND`.
 *  - `settings:agenticServerKey` — the HMAC key the session secrets are derived
 *    under (`order_secret`, hand-off tokens): 32 random bytes, base64url. Created
 *    on first use, NEVER shown or accepted by the Settings form, and declared
 *    `secret` in {@link AGENTIC_SECRET_SETTINGS_SCHEMA} so a site that spreads that
 *    schema into its descriptor gets it encrypted at rest (ADR-0037).
 *
 * Nothing here logs a value or an error message (fixed lines only).
 */
import { AGENT_SESSION_MIN_SERVER_KEY_BYTES } from "@urumi.ai/otta-domain";
import { base64UrlDecode, randomBase64Url } from "@urumi.ai/otta-store-emdash";
import type { SecretSettingFieldSpec } from "../payment-secrets.js";
import type { PluginContext } from "../types.js";

export const AGENTIC_ENABLED_KEY = "settings:agenticEnabled";
export const AGENTIC_SERVER_KEY_KEY = "settings:agenticServerKey";

/**
 * The `admin.settingsSchema` entry that makes EmDash encrypt the server key at
 * rest (ADR-0037), keyed by the setting's name without its `settings:` prefix.
 * Kept apart from `PAYMENT_SECRET_SETTINGS_SCHEMA`: the key is not a payment
 * credential, the Settings form never writes it, and the payment-secret
 * re-encryption marker is not this key's to change.
 */
export const AGENTIC_SECRET_SETTINGS_SCHEMA: Readonly<Record<string, SecretSettingFieldSpec>> = {
	agenticServerKey: {
		type: "secret",
		label: "Agentic checkout server key",
		description: "Generated by Otta on first use; never shown. Saved encrypted.",
	},
};

/** Whether agentic checkout is on. FAIL-SOFT to off (a failed read is logged). */
export async function readAgenticEnabled(ctx: PluginContext): Promise<boolean> {
	try {
		return (await ctx.kv.get<unknown>(AGENTIC_ENABLED_KEY)) === true;
	} catch {
		console.error("[otta] agentic: the enabled setting could not be read; agentic checkout is off");
		return false;
	}
}

/** The raw key bytes of a stored value, or `null` when it is not a usable key. */
function keyBytes(stored: unknown): Uint8Array | null {
	if (typeof stored !== "string") return null;
	const bytes = base64UrlDecode(stored);
	return bytes !== null && bytes.byteLength >= AGENT_SESSION_MIN_SERVER_KEY_BYTES ? bytes : null;
}

/**
 * The server key's bytes, created on first use. FAIL-CLOSED: `null` (logged, no
 * value) when it cannot be read or saved, or a stored value is not a usable key —
 * the caller then refuses as unavailable. A stored but unusable value is NEVER
 * overwritten: replacing it would rotate the key and kill every outstanding
 * `order_secret`. Racing first uses converge on one key: the insert is a
 * compare-and-set against no value where the host offers it, and the winner is
 * re-read either way.
 */
export async function readAgenticServerKey(ctx: PluginContext): Promise<Uint8Array | null> {
	try {
		const stored = await ctx.kv.get<unknown>(AGENTIC_SERVER_KEY_KEY);
		if (stored !== null && stored !== undefined) return unusable(keyBytes(stored));
		const fresh = randomBase64Url(32);
		if (ctx.kv.compareAndSet !== undefined) {
			await ctx.kv.compareAndSet(AGENTIC_SERVER_KEY_KEY, null, fresh);
		} else {
			await ctx.kv.set(AGENTIC_SERVER_KEY_KEY, fresh);
		}
		return unusable(keyBytes(await ctx.kv.get<unknown>(AGENTIC_SERVER_KEY_KEY)));
	} catch {
		console.error(
			"[otta] agentic: the server key could not be read or saved; agentic checkout is unavailable",
		);
		return null;
	}
}

function unusable(bytes: Uint8Array | null): Uint8Array | null {
	if (bytes === null) {
		console.error(
			"[otta] agentic: the stored server key is not usable; agentic checkout is unavailable",
		);
	}
	return bytes;
}
